"""Turn frozen evaluation rows into the report (ADR 0013). Pure: same rows, same text.

Frozen rows (one per evaluated edit): wiki_id, rev_id, hour (the edit's UTC hour), language_group,
label ('damaging' or 'ok'), rules_score, wikimedia_probability (null if Wikimedia has no score).
"""

from dataclasses import dataclass

import numpy as np

from editguard.evaluation.metrics import Comparison, Ranking, paired_bootstrap
from editguard.evaluation.protocol import BUDGET, MIN_DAMAGING, RESAMPLES, SEED


@dataclass(frozen=True)
class Rows:
    """Frozen rows as arrays, sorted by (wiki_id, rev_id) so every run sees the same order."""

    wiki_id: np.ndarray
    hour: np.ndarray
    language_group: np.ndarray
    damaging: np.ndarray
    rules_score: np.ndarray
    wikimedia: np.ndarray  # NaN where Wikimedia has no score


@dataclass(frozen=True)
class Segment:
    name: str
    scored: int  # edits in the segment
    covered: int  # of those, with a Wikimedia score (the compared set)
    damaging: int  # damaging edits in the compared set
    comparison: Comparison | None  # None: fewer than MIN_DAMAGING damaging edits


def evaluate(rows: Rows, name: str, mask: np.ndarray, resamples: int = RESAMPLES) -> Segment:
    """rules-v0 against Wikimedia on the edits in mask that both models scored."""
    covered = mask & ~np.isnan(rows.wikimedia)
    damaging = int(rows.damaging[covered].sum())
    if damaging < MIN_DAMAGING:
        return Segment(name, int(mask.sum()), int(covered.sum()), damaging, None)
    hours, hour_index = np.unique(rows.hour[covered], return_inverse=True)
    bad = rows.damaging[covered]
    comparison = paired_bootstrap(
        Ranking(rows.rules_score[covered], bad, hour_index),
        Ranking(rows.wikimedia[covered], bad, hour_index),
        n_hours=len(hours),
        damaging_count=damaging,
        edit_count=int(covered.sum()),
        resamples=resamples,
        seed=SEED,
        budget=BUDGET,
    )
    return Segment(name, int(mask.sum()), int(covered.sum()), damaging, comparison)


def segments(rows: Rows, resamples: int = RESAMPLES) -> list[Segment]:
    return [
        evaluate(rows, "English, bot-miss", rows.language_group == "english", resamples),
        evaluate(rows, "Indian languages, pooled", rows.language_group == "indian", resamples),
        evaluate(rows, "Bengali", rows.wiki_id == "bnwiki", resamples),
    ]


def pct(x: float) -> str:
    return f"{100 * x:.1f}%"


def headline_row(s: Segment) -> str:
    c = s.comparison
    if c is None:
        return (
            f"| {s.name} | {s.covered:,} | {s.damaging:,} | insufficient data "
            f"(< {MIN_DAMAGING} damaging) | | |"
        )
    diff = f"{100 * c.difference:+.1f} pts ({100 * c.low:+.1f}, {100 * c.high:+.1f})"
    return (
        f"| {s.name} | {c.edits:,} | {c.damaging:,} | {pct(c.editguard)} | {pct(c.baseline)} "
        f"| {diff} |"
    )


def render(meta: dict[str, str], segs: list[Segment], development: bool) -> str:
    """The report as Markdown. meta: snapshot, committed_at, window, score_version, rows_sha256."""
    english = segs[0]
    lines = []
    if development:
        lines += [
            "> **Development report: not the result.** These days are outside the pre-registered",
            "> test window (ADR 0013); they are for building and checking the pipeline only.",
            "",
        ]
    lines += [
        "# Results" if not development else "# Development report",
        "",
        "> Generated by `make report`. Do not edit by hand.",
        "",
        f"- Label snapshot: `{meta['snapshot']}` (gold.fact_label, committed "
        f"{meta['committed_at']}) · Score version: `{meta['score_version']}`",
        f"- {'Test' if not development else 'Development'} days (UTC): {meta['window']}",
        f"- Frozen rows: `{meta['rows_path']}` (SHA-256 `{meta['rows_sha256'][:16]}…`)",
        f"- Budget: top {pct(BUDGET)} of edits by score; ties at the cut get fractional credit."
        f" Interval: paired bootstrap over hours, {RESAMPLES:,} resamples, seed {SEED}.",
        "",
        "## Headline",
        "",
        "| Segment | Edits scored | Damaging | EditGuard recall @2% | Baseline recall @2% "
        "| Difference (95% CI) |",
        "| --- | --- | --- | --- | --- | --- |",
        *[headline_row(s) for s in segs],
        "",
        (
            f"Baseline coverage of scored English edits: {pct(english.covered / english.scored)}."
            if english.scored
            else "Baseline coverage: no English edits."
        )
        + " Comparison uses the intersection only. EditGuard is `rules-v0` (no model yet);"
        " the baseline is Wikimedia's revert-risk model.",
        "",
    ]
    return "\n".join(lines)
